async function routeEngineFixtures(page: Page, ver: string) {
  const files: Record<string, Buffer> = {
    [`${ver}/app/taxon.parquet`]: ENGINE_TAXON,
    [`${ver}/app/zone_taxon.parquet`]: ENGINE_ZONE_TAXON,
    [`${ver}/app/taxonomy.parquet`]: ENGINE_TAXONOMY,
  };
  for (let t = 0; t < 4; t++) {
    files[`${ver}/app/cell/tile=${t}/data_0.parquet`] = CELL_TILES[t];
    files[`${ver}/serve/cell_model/tile=${t}/data_0.parquet`] = CELL_MODEL_TILES[t];
  }
  await page.route(
    (url) =>
      url.href.startsWith(BUCKET) && (url.href.includes("/app/") || url.href.includes("/serve/")),
    (route) => {
      const path = route.request().url().slice(BUCKET.length);
      const body = files[path];
      if (!body) return route.fallback();
      return route.fulfill({ status: 200, contentType: "application/octet-stream", body });
    },
  );
}

