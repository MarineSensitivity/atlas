test.describe("exports", () => {
  test("Download HTML produces a self-contained file", async ({ page }) => {
    await gotoReport(page, { ver: "v9", preview: true });
    const [download] = await Promise.all([
      page.waitForEvent("download"),
      page.getByRole("button", { name: "Download HTML" }).click(),
    ]);
    expect(download.suggestedFilename()).toMatch(/^PREVIEW_MarineSensitivity_.*\.html$/);
  });

  test("Print stylesheet: the watermark is visible only under print media", async ({ page }) => {
    await gotoReport(page, { ver: "v9", preview: true });
    await expect(page.locator(".print-watermark")).not.toBeVisible();
    await page.emulateMedia({ media: "print" });
    await expect(page.locator(".print-watermark")).toBeVisible();
    await expect(page.locator(".export-bar")).toBeHidden();
  });

  // fix round 1, item 2d: the downloaded HTML opens with the network cut off entirely and still
  // shows map, flowers and tables -- proves the export is genuinely self-contained, not merely
  // "worked while the same tab's cache was warm".
  test("Download HTML opens OFFLINE (context.offline) and shows map, flowers and tables", async ({
    page,
    browser,
  }) => {
    await gotoReport(page, { ver: "v9", preview: true });
    await expect(page.locator(".progress-line")).toContainText("Done");
    // let the map's own PNG capture (idle + two animation frames) land before downloading, or the
    // exported document's .map-print would still show "Map rendering...".
    await expect(page.locator(".map-print img")).toBeVisible({ timeout: 15_000 });

    const [download] = await Promise.all([
      page.waitForEvent("download"),
      page.getByRole("button", { name: "Download HTML" }).click(),
    ]);
    // `download.path()` is Playwright's OWN internal artifact path, with no `.html` extension --
    // opened directly via `file://`, Chromium cannot infer the MIME type and renders it as plain
    // text (measured: a literal `<pre>&lt;!doctype html&gt;...`). `saveAs()` to a real `.html`
    // path is what a person's browser download would actually give the file, and what makes
    // `file://` navigation treat it as HTML.
    const savedPath = test.info().outputPath("downloaded-report.html");
    await download.saveAs(savedPath);

    // `context({offline:true})` also blocks the file:// navigation itself on some platforms
    // (measured) -- the actual property under test is "makes zero http(s) requests", which is
    // asserted directly by routing every http(s) URL to a hard abort instead.
    const offlineContext = await browser.newContext();
    try {
      const offlinePage = await offlineContext.newPage();
      const networkRequests: string[] = [];
      await offlinePage.route(/^https?:\/\//, (route) => {
        networkRequests.push(route.request().url());
        return route.abort();
      });
      const errors: string[] = [];
      offlinePage.on("console", (m) => m.type() === "error" && errors.push(m.text()));
      await offlinePage.goto(`file://${savedPath}`);
      await expect(offlinePage.locator("figure.flower-panel")).toHaveCount(2);
      await expect(offlinePage.locator(".map-print img")).toBeVisible();
      await expect(
        offlinePage.locator("table", { hasText: "Mean component and overall scores" }),
      ).toBeVisible();
      expect(networkRequests).toEqual([]);
      // a self-contained document ships no <script> at all, so there is nothing to error --
      // any console error here would mean it tried (and failed) to reach the network.
      expect(errors).toEqual([]);
    } finally {
      await offlineContext.close();
    }
  });
});

